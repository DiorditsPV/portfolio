// Отсев шума из выпуска Agents Weekly при публикации в журнал.
//
// Выпуск ценен тем, что читатель может применить: новая возможность, изменившееся
// поведение, риск. Всё, что отвечает только на вопрос «что поменялось в настройках
// и версиях», — шум: имена переменных окружения, флаги, переименованные команды,
// подвинутые лимиты, требуемые версии рантайма. Такой текст журнал в выпуске не
// хранит, даже если он есть в исходнике.
//
// Отсев детерминированный и намеренно узкий: он убирает только то, что шумом
// является по самой своей форме, и не пытается судить о смысле.
//
//   1. Свёрнутый блок «Остальные изменения CLI» убирается целиком. Главное из
//      релизов стоит над ним тремя-пятью строками; блок по определению содержит
//      то, что главным не стало, — хвост журнала изменений.
//
//   2. В описаниях позиций каталога убираются короткие предложения, которые
//      целиком состоят из требования или способа установки: «Нужен Node.js 20+.»,
//      «Ставится через npx skills add.», «Лицензия MIT.». Длинное предложение не
//      трогается: в нём требование обычно стоит рядом с содержанием. Предложение
//      с предупреждением («не проверяли», «curl | sh», «автор предупреждает») не
//      трогается никогда: это риск, а не шум.
//
// Отсев идемпотентен: повторный проход по уже очищенному выпуску ничего не меняет.

const text = html => html.replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ').trim();

// Предложение-требование: начинается с одного из этих слов.
// Граница слова задана явно: \b в регулярных выражениях JS кириллицу словом не считает.
const REQUIREMENT = /^(Нуж(ен|на|но|ны)|Требу(ет|ют)ся|Понадоб[а-яё]*|Зависимост[а-яё]*|Став(ит|ят)ся|Установка|Устанавлива(ет|ют)ся|Лицензия)(?![а-яё])/i;
// Предупреждение: такое предложение остаётся при любой форме.
const WARNING = /предупрежд|не провер|curl|осторожн|опасн|вредонос|токен|ключ[а-я]* (уход|отправ|переда)|наружу|сломать|риск/i;
const MAX_NOISE_SENTENCE = 90;     // длиннее — в предложении есть что-то кроме требования

const isNoise = sentence => {
  const t = text(sentence);
  return t.length <= MAX_NOISE_SENTENCE && REQUIREMENT.test(t) && !WARNING.test(t);
};

// Граница предложения: точка, пробел, заглавная буква, кавычка или тег.
const SENTENCE_GAP = /(?<=[.!?])\s+(?=[А-ЯЁA-Z«<])/;

function cleanDescription(inner) {
  const parts = inner.split(SENTENCE_GAP);
  const kept = parts.filter(s => !isNoise(s));
  // Описание, состоявшее из одних требований, остаётся как было: пустая позиция хуже шумной.
  return kept.length && kept.length < parts.length ? { html: kept.join(' '), dropped: parts.length - kept.length } : { html: inner, dropped: 0 };
}

export function filterDigest(html) {
  const report = { folds: 0, sentences: 0 };

  html = html.replace(/<details class="method-fold">\s*<summary>\s*Остальные изменения CLI[\s\S]*?<\/details>\s*/g, () => {
    report.folds++;
    return '';
  });

  const clean = (whole, open, inner, close) => {
    const r = cleanDescription(inner);
    report.sentences += r.dropped;
    return open + r.html + close;
  };
  // Развёрнутые позиции каталога: абзац внутри .item. Короткие: span.desc в списке «Коротко».
  html = html.replace(/(<div class="item">[\s\S]*?<p>)([\s\S]*?)(<\/p>)/g, clean);
  html = html.replace(/(<span class="desc">)([\s\S]*?)(<\/span>\s*<\/li>)/g, clean);

  return { html, report };
}
